def split_sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=。)", text)
    return [p for p in parts if p.strip()]

def clean(code: str, text: str) -> str:
    text = (text or "").strip()
    if not text:
        return ""
    if code in OVERRIDE:
        return OVERRIDE[code]
    sents = split_sentences(text)
    if code in DROP_FIRST:
        return "".join(sents[DROP_FIRST[code]:]).strip()
    keep = [s for s in sents if not any(m in s for m in STALE)]
    out = "".join(keep).strip()
    out = re.sub(r"^(——|—|；|;|，|,)+", "", out).strip()
    return out if len(out) >= 10 else ""

def main(write: bool) -> None:
    rows = list(csv.DictReader(PATH.open(encoding="utf-8-sig")))
    header = list(rows[0].keys())
    changed = cleared = kept = 0
    dump = []
    for r in rows:
        before = (r.get("implied_growth_years") or "").strip()
        if not before:
            continue
        after = clean(r["security_code"], before)
        if after != before:
            changed += 1
            if not after:
                cleared += 1
            else:
                kept += 1
        dump.append(f"##### {r['security_code']} {r['security_name']} | {'CLEARED' if not after else ('TRIMMED' if after != before else 'UNCHANGED')}\nBEFORE: {before}\nAFTER : {after or '∅'}\n")
        r["implied_growth_years"] = after
    Path(sys.argv[2] if len(sys.argv) > 2 else "/dev/null").write_text("\n".join(dump), encoding="utf-8")
    print(f"非空 {len(dump)}，改动 {changed}（清空 {cleared}、保留残句 {kept}），未动 {len(dump)-changed}")
    if write:
        with PATH.open("w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, fieldnames=header); w.writeheader(); w.writerows(rows)
        print("已写盘")

if __name__ == "__main__":
    main(write=(sys.argv[1] == "--write"))
