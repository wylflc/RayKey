"""Build oi214_proposed_originals.csv in the exact column format of
data/reference/panel_restatement_originals.csv.

Inputs below are transcribed from the ORIGINAL periodic reports (page refs in `src`).
Derived fields:
  bps            = original parent equity / period-end share capital (same convention as vendor BPS)
  op_cashflow_ps = original OCF / period-end share capital
  gross_margin   = (营业收入 - 营业成本) / 营业收入 * 100   (matches vendor XSMLL, e.g. 000895 FY2009)
  netprofit_qoq / revenue_qoq : carried from the current panel row (not read by the band builder)
Fields given as the literal string 'CUR' are carried from the current panel row (reason in note).
"""
import csv
from decimal import Decimal, getcontext

getcontext().prec = 40
OUT = '/gpfs/scratch1/nodespecific/tcn441/zwang.27284302/claude-66633/-gpfs-scratch1-shared-zwang-mm-quant-RayKey/be4702a1-b00c-45e2-9cec-3beb6af4945d/scratchpad/oi214'
REF = '/gpfs/scratch1/shared/zwang/mm_quant/RayKey/data/reference/panel_restatement_originals.csv'
FIELDS = next(csv.reader(open(REF, encoding='utf-8')))
U = 'http://static.cninfo.com.cn/finalpage/'
REVIEWED = '2026-09-28'

cur = {}
for r in csv.DictReader(open(OUT + '/panel_cache.csv', encoding='utf-8')):
    if not r['_file'].startswith('superseded'):
        cur[(r['security_code'], r['report_date'])] = r


def D(x):
    return Decimal(str(x).replace(',', ''))


def fmt(x, nd):
    q = Decimal(1).scaleb(-nd)
    s = format(x.quantize(q), 'f')
    return s.rstrip('0').rstrip('.') if '.' in s else s


ROWS = []


def row(code, rd, notice, np_, rev, eps, deps, roe, np_yoy, rev_yoy, sa, orig, corr, note,
        equity=None, shares=None, cost=None, ocf=None, bps=None, gm=None, ocfps=None):
    c = cur[(code, rd)]
    out = {k: '' for k in FIELDS}
    out.update(security_code=code, security_name=c['security_name'], report_date=rd, notice_date=notice,
               parent_netprofit=np_, total_operate_income=rev, basic_eps=eps)
    out['deduct_basic_eps'] = c['deduct_basic_eps'] if deps == 'CUR' else deps
    if bps == 'CUR':
        out['bps'] = c['bps']
    else:
        out['bps'] = fmt(D(equity) / D(shares), 12)
    out['weightavg_roe'] = c['weightavg_roe'] if roe == 'CUR' else roe
    if gm == 'CUR':
        out['gross_margin'] = c['gross_margin']
    else:
        out['gross_margin'] = fmt((D(rev) - D(cost)) / D(rev) * 100, 10)
    if ocfps == 'CUR':
        out['op_cashflow_ps'] = c['op_cashflow_ps']
    else:
        out['op_cashflow_ps'] = fmt(D(ocf) / D(shares), 12)
    out['netprofit_yoy'] = c['netprofit_yoy'] if np_yoy == 'CUR' else np_yoy
    out['revenue_yoy'] = c['revenue_yoy'] if rev_yoy == 'CUR' else rev_yoy
    out['netprofit_qoq'] = c['netprofit_qoq']
    out['revenue_qoq'] = c['revenue_qoq']
    out.update(superseded_at=sa, original_url=U + orig, correction_url=U + corr, reviewed_at=REVIEWED, note=note)
    ROWS.append(out)


